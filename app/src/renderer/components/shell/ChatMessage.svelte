<script lang="ts">
  /**
   * One turn in the chat column (#48, `docs/research/collab-doc.md` §4).
   *
   * The asymmetry the flow's thread established is kept: **what the learner wrote is a block,
   * what an agent wrote is a card with its own rule in that agent's colour.** Ellie is green and
   * Max is red, the same green and red their cursors and their edits wear in the document, so
   * the two surfaces read as one room rather than as a chat next to a file.
   *
   * Three things this component is responsible for making legible, all of them §4's:
   *
   *  1. **Colour is never the only signal** (product-design.md §C2 rule 1). Every card carries
   *     the agent's name *and* their role word, and Max's rule is dashed as well as red.
   *  2. **The rule that decided the turn**, where there is one worth naming — the visible-rules
   *     claim the brief rests on. `chatTag()` holds the list and the argument for the short list.
   *  3. **Ellie's guess** (§4.3), which is the one turn in the app that may be wrong on purpose.
   *     It gets a banner rather than a footnote: a learner who reads a hedged wrong answer and
   *     leaves is the risk §1 names, and the closure rule is the other half of the answer to it.
   */
  import type { MessageView } from '../../../shared/types.js';
  import { aiBody } from '../../lib/aitext.js';
  import { EMPTY_TURN_LINE, emptyBody, metaAlwaysOn, metaParts } from '../../lib/flowchat.js';
  import { monogram } from '../../lib/labels.js';
  import { clockTime } from '../../lib/time.js';
  import { AGENT_HUE, AGENT_NAME, AGENT_ROLE_WORD, agentOf, chatTag } from '../../lib/chatview.js';
  import CostMeter from '../cost/CostMeter.svelte';

  let {
    message,
    /** A provisional body streamed in ahead of `turn.released`. */
    streaming = null,
    /** The deck's page numbers, so a `p. N` in the grounds becomes a button. */
    pages = [],
    onpage,
  }: {
    message: MessageView;
    streaming?: string | null;
    pages?: readonly number[];
    onpage?: (page: number) => void;
  } = $props();

  const agent = $derived(agentOf(message));
  const isLearner = $derived(message.speaker.kind === 'student');
  const isReference = $derived(message.speaker.kind === 'reference');
  const hue = $derived(agent ? AGENT_HUE[agent] : isLearner ? 'var(--indigo)' : 'var(--muted)');
  const name = $derived(
    agent
      ? (message.speaker.kind === 'agent' ? message.speaker.displayName : AGENT_NAME[agent])
      : isReference
        ? 'REFERENCE'
        : 'You',
  );
  const parsed = $derived(aiBody(streaming ?? message.body, { pages }));
  const empty = $derived(emptyBody(streaming ?? message.body, streaming !== null));
  const tag = $derived(chatTag(message.decidedBy));
  const guess = $derived(tag?.kind === 'guess');
  const meta = $derived(metaParts(message));
  const loud = $derived(metaAlwaysOn(message.backend));

  /**
   * A click anywhere in the body, looking for a `p. N` citation.
   *
   * Delegated because the body is `@html` and there is no Svelte handler to attach to a button
   * `aitext.ts` wrote. The only thing trusted here is `data-page`, written from a parsed integer
   * that is in the deck — so the worst a model can do is cite a page that exists.
   */
  function onBodyClick(e: MouseEvent): void {
    const hit = (e.target as HTMLElement | null)?.closest?.('[data-page]');
    const page = Number(hit?.getAttribute('data-page') ?? '');
    if (!Number.isInteger(page) || page <= 0) return;
    e.stopPropagation();
    onpage?.(page);
  }
</script>

{#if isLearner}
  <!-- The learner's own words, full width and indigo-tinted: the asymmetry of `pivot-spec.md`
       §B2, kept, because what the learner wrote is the thing that counts for progress. -->
  <article class="mine" data-msg-id={message.id}>
    <header>
      <span class="label-caps">You</span>
      <span class="gap"></span>
      <span class="time" aria-hidden="true">{clockTime(message.createdAt)}</span>
    </header>
    <p>{message.body}</p>
  </article>
{:else}
  <article
    class="ai"
    class:reference={isReference}
    class:tester={agent === 'max'}
    class:guess
    data-msg-id={message.id}
    style="--hue: {hue}"
  >
    {#if guess}
      <!-- §4.3, said before the words rather than after them. -->
      <p class="guessbar" title={tag?.title}>{tag?.label}</p>
    {/if}

    <header class="head">
      {#if agent}
        <span class="avatar" class:ringed={agent === 'max'} aria-hidden="true">{monogram(name)}</span>
        <span class="label-caps name">{name} · {AGENT_ROLE_WORD[agent]}</span>
      {:else}
        <span class="label-caps name ref">REFERENCE</span>
      {/if}
      {#if message.byRule}
        <span class="rule-tag" title="Written by a rule, not generated by a model">by rule</span>
      {/if}
      {#if tag && !guess}
        <span class="rule-tag decided" title={tag.title}>{tag.label}</span>
      {/if}
      <span class="gap"></span>
      <span class="time" aria-hidden="true">{clockTime(message.createdAt)}</span>
    </header>

    {#if empty}
      <p class="empty">{EMPTY_TURN_LINE}</p>
    {:else}
      <!-- svelte-ignore a11y_no_static_element_interactions -->
      <!-- svelte-ignore a11y_click_events_have_key_events -->
      <div class="body" onclick={onBodyClick}>
        <!-- eslint-disable-next-line svelte/no-at-html-tags -->
        {@html parsed.html}
      </div>
    {/if}

    {#if parsed.handBack}
      <hr class="rule" />
      <p class="handback">{parsed.handBack}</p>
    {/if}

    {#if streaming !== null}
      <span class="caret" aria-hidden="true"></span>
    {/if}

    {#if message.stopped}
      <p class="stopped">You stopped this reply.</p>
    {/if}

    {#if meta.length > 0}
      <p class="meta" class:loud>{meta.join(' · ')}</p>
    {/if}

    <!-- What this reply cost (#42 item C). Nothing at all for a rule-written line, a message
         older than migration 021, or the provisional streaming card — none of them has a row. -->
    <CostMeter messageId={message.id} />
  </article>
{/if}

